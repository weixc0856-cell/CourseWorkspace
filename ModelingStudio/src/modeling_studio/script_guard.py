from __future__ import annotations

import ast
from pathlib import Path

ALLOWED_IMPORTS = {"bpy", "bmesh", "mathutils", "math", "random"}
FORBIDDEN_NAMES = {
    "open",
    "eval",
    "exec",
    "compile",
    "__import__",
    "input",
    "getattr",
    "setattr",
    "delattr",
    "globals",
    "locals",
    "vars",
    "__builtins__",
}
FORBIDDEN_ATTR_PREFIXES = (
    "bpy.ops.wm",
    "bpy.ops.export_scene",
    "bpy.ops.import_scene",
    "bpy.ops.script",
    "bpy.ops.preferences",
    "bpy.data.libraries",
    "bpy.utils",
)
MAX_LINES = 500
MAX_BYTES = 80_000


class ScriptRejected(ValueError):
    pass


def _chain(node: ast.AST) -> str:
    parts = []
    current = node
    while isinstance(current, ast.Attribute):
        parts.append(current.attr)
        current = current.value
    if isinstance(current, ast.Name):
        parts.append(current.id)
    return ".".join(reversed(parts))


def guard_script(code: str) -> None:
    if len(code.encode("utf-8")) > MAX_BYTES:
        raise ScriptRejected(f"script exceeds {MAX_BYTES} bytes")
    lines = code.count("\n") + 1
    if lines > MAX_LINES:
        raise ScriptRejected(f"script exceeds {MAX_LINES} lines")
    try:
        tree = ast.parse(code)
    except SyntaxError as exc:
        raise ScriptRejected(f"syntax error: {exc}") from exc

    build_functions = [
        node
        for node in tree.body
        if isinstance(node, ast.FunctionDef) and node.name == "build"
    ]
    if not build_functions:
        raise ScriptRejected("script must define a top-level function build()")
    build = build_functions[0]
    if build.args.args or build.args.kwonlyargs or build.args.vararg or build.args.kwarg:
        raise ScriptRejected("build() must take no arguments")

    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                root = alias.name.split(".")[0]
                if root not in ALLOWED_IMPORTS:
                    raise ScriptRejected(f"import not allowed: {alias.name}")
        elif isinstance(node, ast.ImportFrom):
            module = node.module or ""
            root = module.split(".")[0]
            if node.level != 0 or root not in ALLOWED_IMPORTS:
                raise ScriptRejected(f"import not allowed: from {module}")
        elif isinstance(node, ast.Name):
            if node.id in FORBIDDEN_NAMES:
                raise ScriptRejected(f"forbidden name: {node.id}")
            if node.id.startswith("__"):
                raise ScriptRejected(f"dunder name not allowed: {node.id}")
        elif isinstance(node, ast.Attribute):
            if node.attr.startswith("__"):
                raise ScriptRejected(f"dunder attribute not allowed: {node.attr}")
            chain = _chain(node)
            for prefix in FORBIDDEN_ATTR_PREFIXES:
                if chain == prefix or chain.startswith(prefix + "."):
                    raise ScriptRejected(f"forbidden API: {chain}")
        elif isinstance(node, (ast.Global, ast.Nonlocal)):
            raise ScriptRejected("global/nonlocal declarations are not allowed")


def extract_code(text: str) -> str:
    import re

    fenced = re.search(r"```(?:python)?\s*(.*?)```", text, re.S)
    code = fenced.group(1) if fenced else text
    return code.strip() + "\n"


def write_script(path: Path, code: str, *, model: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    header = (
        "# Generated by ModelingStudio. Do not edit by hand;\n"
        f"# regenerate from model_plan.json (model: {model}).\n"
    )
    path.write_text(header + code, encoding="utf-8")
