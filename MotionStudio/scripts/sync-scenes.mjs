#!/usr/bin/env node
// Regenerate src/scenes.generated.js from the scene directories.
//
// The registry used to be a hand-written list of course scenes. Scenes now live
// in the content root (linked into src/scenes), so the list is derived from the
// filesystem instead: any directory with a .tsx scene works, and the tracked
// source names no course.
import {readdir, writeFile} from 'node:fs/promises';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, '..');
const scenesRoot = path.join(projectRoot, 'src', 'scenes');
const target = path.join(projectRoot, 'src', 'scenes.generated.js');

const entries = [];
for (const dir of await readdir(scenesRoot, {withFileTypes: true})) {
  const dirPath = path.join(scenesRoot, dir.name);
  let files = [];
  try {
    files = await readdir(dirPath);
  } catch {
    continue;
  }
  for (const file of files.sort()) {
    if (!file.endsWith('.tsx')) continue;
    const stem = file.replace(/\.tsx$/, '');
    entries.push({
      id: stem.replace(/_/g, '-'),
      relative: `./scenes/${dir.name}/${stem}`,
    });
  }
}

entries.sort((a, b) => a.id.localeCompare(b.id));
const imports = entries
  .map((entry, index) => `import scene${index} from '${entry.relative}?scene';`)
  .join('\n');
const registry = entries.map((entry, index) => `  '${entry.id}': scene${index},`).join('\n');

await writeFile(
  target,
  `// Generated by scripts/sync-scenes.mjs. Do not edit; do not commit.\n` +
    `${imports}\n\nexport const scenes = {\n${registry}\n};\n`,
  'utf8',
);
console.log(`scenes: ${entries.length} -> ${path.relative(projectRoot, target)}`);
